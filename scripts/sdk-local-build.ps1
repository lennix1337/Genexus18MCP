<#
.SYNOPSIS
Specifies, generates and compiles objects of a disposable test KB with the
installed GeneXus SDK's own MSBuild tasks, outside the MCP Gateway/Worker.

.DESCRIPTION
The standard route for an SDK build "por fora" (see docs/sdk-local-msbuild.md):

  1. 32-bit .NET Framework MSBuild runs a generated project that imports the
     installed Genexus.Tasks.targets:
     OpenKnowledgeBase -> SpecifyOneOnly | SpecifyAllOnly -> GenerateOnly -> CloseKnowledgeBase.
  2. `dotnet msbuild -t:Build;Publish` (Rebuild;Publish with -ForceRebuild)
     compiles the SDK-generated projects under <KB>\<environment>\build whose
     sources this run regenerated (or -Project) and publishes them to the
     environment's web\bin, as the IDE does. -NoPublish stops after Build.

It never uses BuildOne, BuildAll, IdeWebBuildAndDeploy, Reorganize or any
deploy task. Those include deploy-to-Cloud on a Trial install (DEPLOY_CLOUD is
forced to Yes) and can apply a pending database reorganization (#749). The
generated project is checked against a task allow-list before it runs.

Only `C:\KBs\*teste*` Knowledge Bases are accepted. Evidence (project, logs and
summary.json) goes to -EvidenceDir, by default scratchpad\sdk-local-build\<stamp>.
-PlanOnly prints the plan and the generated project without touching any file.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$KbPath,
    [string[]]$Object = @(),
    [switch]$All,
    [ValidateSet('Specify', 'Generate', 'Compile')][string]$Through = 'Compile',
    [switch]$ForceRebuild,
    [string[]]$Project = @(),
    [switch]$NoPublish,
    [string]$GeneXusDir = $(if ($env:GX_PROGRAM_DIR) { $env:GX_PROGRAM_DIR } else { 'C:\Program Files (x86)\GeneXus\GeneXus18' }),
    [string]$FixtureManifest,
    [string]$EvidenceDir,
    [ValidateRange(1, 86400)][int]$TimeoutSeconds = 3600,
    [switch]$PlanOnly
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$allowedTasks = @('OpenKnowledgeBase', 'SpecifyOneOnly', 'SpecifyAllOnly', 'GenerateOnly', 'CloseKnowledgeBase', 'Message', 'OnError')

function Resolve-TestKbPath([string]$Path) {
    $full = [IO.Path]::GetFullPath($Path).TrimEnd('\', '/')
    $parent = Split-Path -Parent $full
    $leaf = Split-Path -Leaf $full
    if ($parent -ine 'C:\KBs' -or $leaf -notlike '*teste*') {
        throw "Refused KB '$full': only disposable test KBs directly under C:\KBs whose name contains 'teste' are allowed."
    }
    return $full
}

function Assert-ObjectNames([string[]]$Names) {
    foreach ($name in $Names) {
        if ($name -notmatch '^[A-Za-z_][A-Za-z0-9_]*(:[A-Za-z_][A-Za-z0-9_.]*)?$') {
            throw "Refused object name '$name': expected Name or Type:Name (letters, digits, '_' and '.')."
        }
    }
}

function New-LocalBuildProject([string]$TargetsFile, [string]$Kb, [string[]]$Names, [bool]$Everything, [bool]$Force, [bool]$Generate) {
    $esc = { param($v) [Security.SecurityElement]::Escape($v) }
    $forceText = if ($Force) { 'true' } else { 'false' }
    $specify = if ($Everything) {
        "    <SpecifyAllOnly ForceRebuild=`"$forceText`" />"
    } else {
        "    <SpecifyOneOnly ObjectNames=`"$(& $esc ($Names -join ';'))`" ForceRebuild=`"$forceText`" />"
    }
    $lines = @(
        '<Project DefaultTargets="LocalBuild" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">'
        "  <Import Project=`"$(& $esc $TargetsFile)`" />"
        '  <!-- Generated by scripts/sdk-local-build.ps1: specification and generation only.'
        '       No BuildOne, BuildAll, IdeWebBuildAndDeploy, Reorganize or deploy task. -->'
        '  <Target Name="LocalBuild">'
        "    <OpenKnowledgeBase Directory=`"$(& $esc $Kb)`" />"
        '    <Message Importance="high" Text="[SDK-LOCAL] specify start" />'
        $specify
    )
    if ($Generate) {
        $lines += '    <Message Importance="high" Text="[SDK-LOCAL] generate start" />'
        $lines += '    <GenerateOnly />'
    }
    $lines += @(
        '    <Message Importance="high" Text="[SDK-LOCAL] done" />'
        '    <CloseKnowledgeBase />'
        '    <OnError ExecuteTargets="CloseOnError" />'
        '  </Target>'
        '  <Target Name="CloseOnError"><CloseKnowledgeBase /></Target>'
        '</Project>'
    )
    return ($lines -join "`r`n") + "`r`n"
}

function Assert-AllowedTasks([string]$ProjectXml) {
    $doc = [xml]$ProjectXml
    $ns = New-Object Xml.XmlNamespaceManager $doc.NameTable
    $ns.AddNamespace('m', 'http://schemas.microsoft.com/developer/msbuild/2003')
    foreach ($task in $doc.SelectNodes('//m:Target/*', $ns)) {
        if ($allowedTasks -notcontains $task.LocalName) {
            throw "Refused generated project: task '$($task.LocalName)' is not in the local-build allow-list."
        }
    }
}

function Invoke-Logged([string]$FilePath, [string[]]$Arguments, [string]$LogPath, [int]$Seconds) {
    $info = [Diagnostics.ProcessStartInfo]::new($FilePath)
    foreach ($a in $Arguments) { $info.ArgumentList.Add($a) }
    $info.UseShellExecute = $false
    $info.RedirectStandardOutput = $true
    $info.RedirectStandardError = $true
    $watch = [Diagnostics.Stopwatch]::StartNew()
    $process = [Diagnostics.Process]::Start($info)
    $stdout = $process.StandardOutput.ReadToEndAsync()
    $stderr = $process.StandardError.ReadToEndAsync()
    $timedOut = -not $process.WaitForExit($Seconds * 1000)
    if ($timedOut) { $process.Kill($true); $process.WaitForExit() }
    $process.WaitForExit()
    Set-Content -LiteralPath $LogPath -Value ($stdout.Result + $stderr.Result) -Encoding utf8
    $exit = if ($timedOut) { -1 } else { $process.ExitCode }
    return [ordered]@{ command = @($FilePath) + $Arguments; exitCode = $exit; timedOut = $timedOut; wallMs = [math]::Round($watch.Elapsed.TotalMilliseconds); log = $LogPath }
}

function Find-GeneratedProjects([string]$Kb, [datetime]$SinceUtc, [string[]]$Names) {
    $found = @()
    foreach ($envDir in Get-ChildItem -LiteralPath $Kb -Directory) {
        $buildDir = Join-Path $envDir.FullName 'build'
        if (-not (Test-Path -LiteralPath (Join-Path $buildDir 'DotNetCoreBaseProject.targets'))) { continue }
        $webDir = Join-Path $envDir.FullName 'web'
        foreach ($csproj in Get-ChildItem -LiteralPath $buildDir -Filter *.csproj -Recurse -Depth 1) {
            $projectName = $csproj.BaseName
            if ($Names.Count -gt 0) {
                if ($Names -icontains $projectName) { $found += $csproj.FullName }
                continue
            }
            $sources = [regex]::Matches((Get-Content -LiteralPath $csproj.FullName -Raw), 'Include\s*=\s*"\$\(WebDirectory\)\\([^"]+\.cs)"') |
                ForEach-Object { Join-Path $webDir $_.Groups[1].Value }
            if (@($sources | Where-Object { (Test-Path -LiteralPath $_) -and (Get-Item -LiteralPath $_).LastWriteTimeUtc -ge $SinceUtc }).Count -gt 0) {
                $found += $csproj.FullName
            }
        }
    }
    return , $found
}

# `pwsh -File` passes one string per parameter, so accept comma-separated lists too.
$Object = @($Object | ForEach-Object { $_ -split ',' } | ForEach-Object Trim | Where-Object { $_ })
$Project = @($Project | ForEach-Object { $_ -split ',' } | ForEach-Object Trim | Where-Object { $_ })
if ($All -eq ($Object.Count -gt 0)) { throw 'Pass either -Object <names> or -All.' }
if ($Project.Count -gt 0 -and $Through -ne 'Compile') { throw '-Project only applies with -Through Compile.' }
Assert-ObjectNames $Object
$kb = Resolve-TestKbPath $KbPath
$targets = Join-Path $GeneXusDir 'Genexus.Tasks.targets'
$msbuild = Join-Path $env:WINDIR 'Microsoft.NET\Framework\v4.0.30319\MSBuild.exe'
$projectXml = New-LocalBuildProject $targets $kb $Object $All.IsPresent $ForceRebuild.IsPresent ($Through -ne 'Specify')
Assert-AllowedTasks $projectXml

if ($PlanOnly) {
    [ordered]@{ kbPath = $kb; through = $Through; forceRebuild = $ForceRebuild.IsPresent; msbuild = $msbuild; targets = $targets; projectXml = $projectXml } |
        ConvertTo-Json -Depth 4
    exit 0
}

foreach ($required in @($kb, $targets, $msbuild)) {
    if (-not (Test-Path -LiteralPath $required)) { throw "Required path not found: $required" }
}
$fixture = $null
if ($FixtureManifest) {
    . (Join-Path $PSScriptRoot 'live-fixture.ps1')
    $fixture = Get-Content -LiteralPath $FixtureManifest -Raw | ConvertFrom-Json
    Assert-LiveFixture $fixture $kb
}
if (-not $EvidenceDir) {
    $EvidenceDir = Join-Path $repoRoot ('scratchpad\sdk-local-build\' + (Get-Date -Format 'yyyyMMdd-HHmmss'))
}
New-Item -ItemType Directory -Path $EvidenceDir -Force | Out-Null
$projectFile = Join-Path $EvidenceDir 'sdk-local-build.proj'
Set-Content -LiteralPath $projectFile -Value $projectXml -Encoding utf8

$summary = [ordered]@{
    kbPath = $kb
    fixture = if ($fixture) { [ordered]@{ id = $fixture.fixtureId; revision = $fixture.fixtureRevision } } else { $null }
    sdk = [ordered]@{
        dir = $GeneXusDir
        productVersion = (Get-Item -LiteralPath (Join-Path $GeneXusDir 'GeneXus.exe') -ErrorAction SilentlyContinue).VersionInfo.ProductVersion
        tasksFileVersion = (Get-Item -LiteralPath (Join-Path $GeneXusDir 'Genexus.MsBuild.Tasks.dll') -ErrorAction SilentlyContinue).VersionInfo.FileVersion
    }
    objects = if ($All) { '*' } else { $Object }
    through = $Through
    forceRebuild = $ForceRebuild.IsPresent
    startedAtUtc = [datetime]::UtcNow.ToString('o')
    sdkPhase = $null
    compile = @()
    status = 'failed'
}
$sinceUtc = [datetime]::UtcNow.AddSeconds(-2)
$summary.sdkPhase = Invoke-Logged $msbuild @($projectFile, '/nologo', '/nr:false', '/m:1', '/v:normal') (Join-Path $EvidenceDir 'sdk-msbuild.log') $TimeoutSeconds
$failed = $summary.sdkPhase.exitCode -ne 0

if (-not $failed -and $Through -eq 'Compile') {
    $projects = Find-GeneratedProjects $kb $sinceUtc $Project
    if ($Project.Count -gt 0 -and $projects.Count -ne $Project.Count) {
        throw "Requested -Project not found under $kb\*\build: $($Project -join ', ')"
    }
    foreach ($csproj in $projects) {
        $name = [IO.Path]::GetFileNameWithoutExtension($csproj)
        # Build + Publish as the IDE does: the SDK's DotNetCoreBaseProject.targets sets
        # PublishDir to <environment>\web\bin, where the KB runtime loads programs from.
        $compileTargets = if ($ForceRebuild) { 'Rebuild;Publish' } else { 'Build;Publish' }
        $compileTargets = if ($NoPublish) { $compileTargets -replace ';Publish$', '' } else { $compileTargets }
        $dotnetArgs = @('msbuild', $csproj, '-restore', "-t:$compileTargets", '-nologo', '-nr:false', '-v:minimal')
        $result = Invoke-Logged 'dotnet' $dotnetArgs (Join-Path $EvidenceDir "compile-$name.log") $TimeoutSeconds
        $result.project = $csproj
        $summary.compile += $result
        if ($result.exitCode -ne 0) { $failed = $true }
    }
}
$summary.status = if ($failed) { 'failed' } else { 'succeeded' }
$summary.finishedAtUtc = [datetime]::UtcNow.ToString('o')
$summaryPath = Join-Path $EvidenceDir 'summary.json'
$summary | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $summaryPath -Encoding utf8
Write-Output "SDK local build $($summary.status): SDK phase exit $($summary.sdkPhase.exitCode) in $($summary.sdkPhase.wallMs) ms; $($summary.compile.Count) project(s) compiled. Evidence: $summaryPath"
if ($failed) { exit 1 }
exit 0
